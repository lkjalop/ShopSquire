import {test,expect} from './helpers/authenticatedTest';
import {turn} from './helpers/chatTurn';
import {turnViolations} from './helpers/turnOracle';
import path from 'node:path';
import {execFileSync} from 'node:child_process';
import {readFileSync} from 'node:fs';
import {createHash} from 'node:crypto';

const imageIndexes=process.env.ROADMAP_IMAGE_INDEX?[Number(process.env.ROADMAP_IMAGE_INDEX)]:[0,1,2];
for(const index of imageIndexes)test(`image ${index+1} triage and corrections preserve authority and effect state`,async({page},info)=>{
 test.setTimeout(180000);
 const root=process.env.ROADMAP_TEST_ROOT!;
 const names=['macbook.jpg','Dell 15 DC15255.webp','lenovo-pro7.webp'];
 const file=path.join(root,'tests','fixtures','browser_images',names[index]);
 const snapshot=()=>JSON.parse(execFileSync(process.env.ROADMAP_TEST_PYTHON!,['-m','scripts.demo_effect_snapshot'],{cwd:root,env:process.env,timeout:15000}).toString());
 await page.goto('/');await page.getByRole('button',{name:/Ask Me/i}).click({force:true});
 const first=await turn(page,'I need 20 laptops for university under AUD 1500 per laptop.');
 expect(turnViolations(first)).toEqual([]);
 const before=snapshot();
 await page.locator("input[type='file']").last().setInputFiles(file);
 await expect(page.getByRole('img',{name:'attached 1'})).toBeVisible();
 const pending=page.waitForResponse(r=>r.url().includes('/vision/triage')&&!new URL(r.url()).searchParams.has('fast')&&r.request().method()==='POST',{timeout:90000});
 await page.getByPlaceholder('Type your message...').fill('Identify the main object in this image. This image is evidence only. Do not add products or send messages.');
 await page.getByRole('button',{name:'Send message',exact:true}).click();
 const response=await pending;expect(response.ok(),await response.text()).toBe(true);const triage=await response.json();
 expect(triage).toHaveProperty('artifact');
 expect((triage.analysis_state?.degraded_reasons||[]).filter((r:string)=>/vision_provider|model_execution|model_artifact|local_model/.test(r))).toEqual([]);
 await expect(page.getByPlaceholder('Type your message...')).toBeEnabled({timeout:90000});
 const corrected=await turn(page,'Change the laptop quantity to 12, keeping my AUD 1500 per laptop budget.');
 expect(turnViolations(corrected)).toEqual([]);
 expect(corrected.terminal_outcome.commerce_authority).toBe('none');
 expect(corrected.requested_quantity).toBe(12);
 expect(corrected.confirmed_slots.order_quantity).toBe(12);
 expect(corrected.terminal_outcome.canonical_facts.quantity).toBe(12);
 expect(corrected.turn_read_model.shared_constraints.requested_quantity).toBe(12);
 expect(corrected.turn_read_model.commercial_terms.quantity).toBe(12);
 const after=snapshot();expect(after).toEqual(before);
 await info.attach('image-continuity.json',{body:JSON.stringify({file:names[index],sha256:createHash('sha256').update(readFileSync(file)).digest('hex'),triage,corrected,before,after},null,2),contentType:'application/json'});
});
