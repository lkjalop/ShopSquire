import {test,expect} from './helpers/authenticatedTest';
import {turn} from './helpers/chatTurn';
import {qualify,reviewCurrentFixtureStock} from './helpers/currentQualification';

test('ordinary chat drafts the accepted forty-unit shortfall and retains it through market analysis and reload',async({page,context},info)=>{
  test.setTimeout(240000);
  const qualified=await qualify(page,context,info);
  await reviewCurrentFixtureStock(page,qualified);
  await page.getByLabel('Requested units').fill('40');
  const response=page.waitForResponse(r=>r.url().endsWith('/stock-acceptance')&&r.request().method()==='POST');
  await page.getByRole('button',{name:'Accept simulated stock request',exact:true}).click();
  const acceptedResponse=await response;
  expect(acceptedResponse.ok(),await acceptedResponse.text()).toBe(true);
  const accepted=await acceptedResponse.json();
  expect(accepted.requested_quantity).toBe(40);
  expect(accepted.held_quantity).toBe(15);
  expect(accepted.shortfall).toBe(25);
  const draft=await turn(page,'Draft an email to the supplier for the remaining stock shortfall in my current request.');
  await info.attach('ordinary-chat-shortfall-draft.json',{body:JSON.stringify({accepted,draft},null,2),contentType:'application/json'});
  expect(draft.case_id).toBe(qualified.case_id);
  expect(draft.email_draft.requested_quantity).toBe(40);
  expect(draft.email_draft.shortfall).toBe(25);
  expect(draft.email_draft.body).toContain('25 units');
  expect(draft.email_draft.body).toContain('40 units');
  expect(draft.email_draft.dispatch_authorized).toBe(false);
  expect(draft.email_draft.missing_inputs).toEqual(['supplier_contact']);
  expect(draft.read_only_case_task).toBe(true);
  const market=await turn(page,'Give me market intelligence for this current procurement request.');
  await info.attach('ordinary-chat-shortfall-market.json',{body:JSON.stringify(market,null,2),contentType:'application/json'});
  expect(market.case_id).toBe(qualified.case_id);
  expect(market.retained_buyer_facts.requested_quantity).toBe(40);
  expect(['blocked','unavailable']).toContain(market.market_intelligence.delivery_status);
  expect(market.terminal_outcome.commerce_authority).toBe('none');
  await page.reload();
  await page.getByRole('button',{name:/Ask Me/i}).click({force:true});
  const reloaded=await turn(page,'Draft an email to the supplier for the remaining stock shortfall in my current request.');
  await info.attach('ordinary-chat-shortfall-reloaded.json',{body:JSON.stringify(reloaded,null,2),contentType:'application/json'});
  expect(reloaded.case_id).toBe(qualified.case_id);
  expect(reloaded.email_draft.requested_quantity).toBe(40);
  expect(reloaded.email_draft.shortfall).toBe(25);
  expect(reloaded.email_draft.dispatch_authorized).toBe(false);
});
