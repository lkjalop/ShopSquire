import {test,expect} from './helpers/authenticatedTest';
import {terminalTurn as turn} from './helpers/terminalTurn';
import {qualify,reviewCurrentFixtureStock} from './helpers/currentQualification';
import {supplierPanel} from './helpers/supplierPanel';

test('ordinary buyer draft survives independent review, revision, quoted intelligence and reload',async({page,context,browser},info)=>{
  test.setTimeout(240000);
  const tenant='synthetic-electronics';
  const endpoint='/api/v1/admin/inventory/supplier-enquiries';
  await context.setExtraHTTPHeaders({});
  const privileged:string[]=[];
  page.on('request',request=>{
    if(new URL(request.url()).pathname.startsWith('/api/v1/')&&request.headers()['x-api-key'])privileged.push(request.url());
  });
  const qualified=await qualify(page,context,info);
  await reviewCurrentFixtureStock(page,qualified);
  await page.getByLabel('Requested units').fill('40');
  const accepting=page.waitForResponse(r=>r.url().endsWith('/stock-acceptance')&&r.request().method()==='POST');
  await page.getByRole('button',{name:'Accept simulated stock request',exact:true}).click();
  const acceptedResponse=await accepting;
  expect(acceptedResponse.ok(),await acceptedResponse.text()).toBe(true);
  const accepted=await acceptedResponse.json();
  expect([accepted.requested_quantity,accepted.held_quantity,accepted.shortfall]).toEqual([40,15,25]);
  const draft=await turn(page,'Draft an email to the supplier for the remaining stock shortfall. Do not send it.');
  expect(draft.email_draft.shortfall).toBe(25);
  const requesterContext=await browser.newContext(),reviewerContext=await browser.newContext();
  try{
    const author=await requesterContext.newPage(),reviewer=await reviewerContext.newPage();
    await supplierPanel(author,process.env.DEVELOPER_API_KEY!,tenant);
    await supplierPanel(reviewer,process.env.OWNER_API_KEY!,tenant);
    await author.getByLabel('Supplier case ID').fill(accepted.case_id);
    await author.getByLabel('Supplier case revision').fill(String(accepted.case_revision));
    await author.getByLabel('Enquiry reference').fill(`draft-continuity-${Date.now()}`);
    const creating=author.waitForResponse(r=>r.url().endsWith('/supplier-enquiries')&&r.request().method()==='POST');
    await author.getByRole('button',{name:'Draft shortfall enquiry',exact:true}).click();
    const createdResponse=await creating;
    expect(createdResponse.ok(),await createdResponse.text()).toBe(true);
    const created=await createdResponse.json();
    expect(created.message.body).toBe(draft.email_draft.body);
    expect(created.draft_artifact.content_hash).toBe(draft.email_draft.draft_artifact.content_hash);
    await expect(author.getByRole('region',{name:'Exact enquiry message'})).toContainText('25 units');
    await reviewer.getByLabel('Enquiry ID',{exact:true}).fill(created.id);
    await reviewer.getByRole('button',{name:'Load enquiry',exact:true}).click();
    await reviewer.getByRole('button',{name:'Approve enquiry',exact:true}).click();
    await expect(reviewer.getByRole('region',{name:'Supplier enquiries'})).toContainText('Approval: current.');
    await author.getByRole('button',{name:'Load enquiry',exact:true}).click();
    await author.getByLabel('Include buyer budget in supplier message').uncheck();
    await author.getByRole('button',{name:'Save revised draft for review',exact:true}).click();
    await expect(author.getByText('Draft version 2. Changes require fresh independent approval.')).toBeVisible();
    const headers={'x-api-key':process.env.DEVELOPER_API_KEY!,'x-tenant-id':tenant};
    const savedResponse=await requesterContext.request.get(`${endpoint}/${created.id}`,{headers});
    expect(savedResponse.ok()).toBe(true);
    const saved=await savedResponse.json();
    const chatPreview=await turn(page,'Show the supplier email draft for my current request.');
    expect(chatPreview.email_draft.body).toBe(saved.message.body);
    expect(chatPreview.email_draft.draft_artifact).toEqual(saved.draft_artifact);
    expect(chatPreview.email_draft.draft_version).toBe(2);
    expect(chatPreview.email_draft.dispatch_authorized).toBe(false);
    await page.reload();
    await page.getByRole('button',{name:/Ask Me/i}).click({force:true});
    const reloadedPreview=await turn(page,'Show the supplier email draft for my current request.');
    expect(reloadedPreview.email_draft.draft_artifact).toEqual(saved.draft_artifact);
    expect(reloadedPreview.email_draft.draft_version).toBe(2);
    expect(reloadedPreview.retained_buyer_facts.requested_quantity).toBe(40);
    const rejected=await requesterContext.request.post(`${endpoint}/${created.id}/dispatch`,{headers});
    expect(rejected.status()).toBe(409);
    await reviewer.getByRole('button',{name:'Load enquiry',exact:true}).click();
    await expect(reviewer.getByLabel('Include buyer budget in supplier message')).not.toBeChecked();
    await reviewer.getByRole('button',{name:'Approve enquiry',exact:true}).click();
    await reviewer.getByRole('button',{name:'Send through fake transport',exact:true}).click();
    const region=reviewer.getByRole('region',{name:'Supplier enquiries'});
    await expect(region).toContainText('Delivery: sent. Transport attempts: 1.');
    await reviewer.getByText('Simulate a supplier reply',{exact:true}).click();
    const reply={message_id:`continuity-${created.id}`,sender_ref:'fictional-distributor',terms:{
      sku:created.sku,quantity:25,unit_cost_cents:70000,freight_cents:12000,currency:'AUD',
      lead_days:5,minimum_order:1,expires_at:new Date(Date.now()+86400000).toISOString()}};
    await reviewer.getByLabel('Simulated supplier reply').fill(JSON.stringify(reply));
    const replying=reviewer.waitForResponse(r=>r.url().endsWith('/simulated-replies')&&r.request().method()==='POST');
    await reviewer.getByRole('button',{name:'Record simulated reply',exact:true}).click();
    const replyResponse=await replying;
    expect(replyResponse.ok(),await replyResponse.text()).toBe(true);
    const recorded=await replyResponse.json();
    const quote=reviewer.getByTestId(`supplier-quote-${recorded.id}`);
    await quote.getByRole('button').click();
    await expect(quote).toContainText('reviewed');
    const market=await turn(page,'Give me market intelligence on supplier lead times for my current request.');
    expect(market.market_intelligence.delivery_status).toBe('available');
    expect(market.market_intelligence.market_evidence.citations.some((c:any)=>c.source_record_id===recorded.id)).toBe(true);
    expect(market.assistant_message).toContain('5 days');
    expect(market.assistant_message).toContain('simulation only');
    expect(market.retained_buyer_facts.requested_quantity).toBe(40);
    await page.reload();
    await page.getByRole('button',{name:/Ask Me/i}).click({force:true});
    const restored=await turn(page,'Summarise my current quantity and budget without taking any action.');
    expect(restored.case_id).toBe(qualified.case_id);
    expect(restored.retained_buyer_facts.requested_quantity).toBe(40);
    expect(restored.terminal_outcome.commerce_authority).toBe('none');
    expect(privileged,'Buyer browser must not borrow operator credentials').toEqual([]);
    await info.attach('reviewed-draft-and-market.json',{body:JSON.stringify({accepted,draft,created,market,restored},null,2),contentType:'application/json'});
    await info.attach('reviewed-draft-screen',{body:await reviewer.screenshot({fullPage:true}),contentType:'image/png'});
  }finally{
    await requesterContext.close();await reviewerContext.close();
  }
});
