"""Owned Redis isolation and export-failure checks; no application database writes."""
import json
import os
from uuid import uuid4

import pytest

from src.app.platform.tenant_context import set_active_tenant_id, reset_active_tenant_id
from src.app.services.memory import Memory
from src.app.services.user_data_inventory import export_redis, erase_redis


@pytest.mark.integration
def test_actual_redis_preserves_other_controller_and_legacy_data():
    url = os.getenv('TEST_OWNED_PRIVACY_REDIS_URL')
    if not url:
        pytest.skip('Explicit owned Redis is required for controller isolation')
    import redis

    client = redis.Redis.from_url(url, socket_timeout=1, socket_connect_timeout=1)
    namespace = uuid4().hex
    uid = 'owned-privacy-' + namespace
    tenant_a, tenant_b = 'owned-a-' + namespace, 'owned-b-' + namespace
    legacy = f'session:{uid}:kv_state'
    unrelated = 'owned-unrelated:' + namespace
    first, second = Memory(client, tenant_id=tenant_a), Memory(client, tenant_id=tenant_b)
    cleanup = []
    for store in (first, second):
        cleanup.extend([store.scoped_key('kv_state', uid), store.scope(uid).subject_index_key])
    cleanup.extend([legacy, unrelated])
    token = None
    try:
        assert client.ping()
        client.set(legacy, json.dumps({'private': 'LEGACY_CANARY'}))
        client.set(unrelated, 'RETAIN_UNRELATED')
        first.set_kv(uid, {'quantity': 40, 'private': 'CONTROLLER_A'})
        second.set_kv(uid, {'quantity': 90, 'private': 'CONTROLLER_B'})
        token = set_active_tenant_id(tenant_a)
        exported = export_redis(client, uid)
        assert 'LEGACY_CANARY' not in json.dumps(exported)
        assert 'CONTROLLER_B' not in json.dumps(exported)
        assert 'CONTROLLER_A' in json.dumps(exported)

        class FailedValueRead:
            is_shared_backend = True

            def __getattr__(self, name):
                return getattr(client, name)

            def get(self, key):
                if key == first.scoped_key('kv_state', uid):
                    raise ConnectionError('Owned injected read failure')
                return client.get(key)

        with pytest.raises(RuntimeError, match='privacy_memory_export_incomplete'):
            export_redis(FailedValueRead(), uid)
        result = erase_redis(client, uid)
        assert result['complete'] is True
        assert first.get_kv(uid) == {}
        assert second.get_kv(uid)['quantity'] == 90
        assert client.get(legacy) == json.dumps({'private': 'LEGACY_CANARY'}).encode()
        assert client.get(unrelated) == b'RETAIN_UNRELATED'
    finally:
        if token is not None:
            reset_active_tenant_id(token)
        # Every key is generated by this test; no SCAN, prefix wipe or FLUSHDB.
        client.delete(*cleanup)
        assert not any(client.exists(key) for key in cleanup)
        client.close()
